#!/usr/bin/env node
'use strict';

/**
 * scripts/probe-energy-etf-quotes.js
 *
 * One-shot live-hours quote probe for the energy/nuclear ETF shortlist.
 * Fetches bid/ask/last during EU trading hours, computes spreads, and
 * appends findings to docs/research/energy-nuclear-preflight-<date>.md.
 *
 * Read-only. Does NOT touch portfolio.md, holdings.md, trades.md, or any
 * execution path. Safe to schedule via cron.
 *
 * Usage:
 *   node scripts/probe-energy-etf-quotes.js
 *   node scripts/probe-energy-etf-quotes.js --json
 */

const fs = require('fs');
const path = require('path');
const { fetchLatestPrice } = require('../src/brokers/interactive-brokers/pricing');

const SHORTLIST = [
  { label: 'XDWE-Xetra-EUR',  conid: '227263991', symbol: 'XDW0', venue: 'IBIS2',  currency: 'EUR', isin: 'IE00BM67HM91', name: 'Xtrackers MSCI World Energy 1C', ter: 0.25 },
  { label: 'NUUR-AEX-USD',    conid: '825813453', symbol: 'NUUR', venue: 'AEB',    currency: 'USD', isin: 'IE000BMZP0I6', name: 'iShares Nuclear Energy and Uranium Mining', ter: 0.40 },
  { label: 'INRE-Paris-EUR',  conid: '552352705', symbol: 'INRE', venue: 'SBF',    currency: 'EUR', isin: 'IE000U58J0M1', name: 'iShares Global Clean Energy Transition', ter: 0.65 },
];

function spreadPct(bid, ask) {
  if (!bid || !ask || bid <= 0 || ask <= 0 || ask <= bid) return null;
  return ((ask - bid) / ((ask + bid) / 2)) * 100;
}

async function probeOne(spec) {
  try {
    const result = await fetchLatestPrice({ conid: spec.conid, portfolio: 'etf' });
    return {
      label: spec.label,
      conid: spec.conid,
      symbol: spec.symbol,
      venue: spec.venue,
      currency: spec.currency,
      isin: spec.isin,
      name: spec.name,
      ter: spec.ter,
      bid: result.bid ?? null,
      ask: result.ask ?? null,
      last: result.last ?? null,
      close: result.close ?? null,
      spreadPct: spreadPct(result.bid, result.ask),
      ok: result.ok !== false,
      error: null,
    };
  } catch (err) {
    return {
      label: spec.label,
      conid: spec.conid,
      symbol: spec.symbol,
      ok: false,
      error: err.message || String(err),
    };
  }
}

function formatRow(r) {
  if (!r.ok) return `| ${r.label} | conid ${r.conid} | error | ${r.error} |`;
  const bid = r.bid != null ? r.bid.toFixed(4) : '—';
  const ask = r.ask != null ? r.ask.toFixed(4) : '—';
  const last = r.last != null ? r.last.toFixed(4) : '—';
  const spread = r.spreadPct != null ? r.spreadPct.toFixed(2) + '%' : 'n/a';
  const verdict = r.spreadPct == null ? 'closed/illiquid'
    : r.spreadPct < 0.15 ? '✅ tight'
    : r.spreadPct < 0.40 ? '✅ acceptable'
    : r.spreadPct < 1.00 ? '⚠️ wide'
    : '❌ very wide';
  return `| ${r.label} | bid ${bid} ${r.currency} / ask ${ask} | last ${last} | ${spread} | ${verdict} |`;
}

async function main() {
  const args = process.argv.slice(2);
  const jsonMode = args.includes('--json');

  const results = [];
  for (const spec of SHORTLIST) {
    results.push(await probeOne(spec));
  }

  const now = new Date();
  const ts = now.toISOString();
  const dateOnly = ts.slice(0, 10);

  if (jsonMode) {
    console.log(JSON.stringify({ ok: true, probedAt: ts, results }, null, 2));
    return;
  }

  const lines = [];
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push(`## Live-hours probe — ${ts}`);
  lines.push('');
  lines.push('| Listing | Bid / Ask | Last | Spread | Verdict |');
  lines.push('|---|---|---|---|---|');
  for (const r of results) lines.push(formatRow(r));
  lines.push('');

  // Pre-trade-readiness call
  const okCount = results.filter((r) => r.spreadPct != null && r.spreadPct < 0.40).length;
  if (okCount === results.length) {
    lines.push('**Verdict:** All three listings show acceptable live spreads. Pre-trade infrastructure is ready when/if the sleeve is approved.');
  } else if (okCount > 0) {
    lines.push(`**Verdict:** ${okCount}/${results.length} listings show acceptable live spreads. Recheck or pick alternates for the rest.`);
  } else {
    lines.push('**Verdict:** No listing showed an acceptable live spread. Likely off-hours or quote feed issue. Recheck during 09:00–16:30 UTC.');
  }
  lines.push('');

  const docPath = path.resolve(__dirname, '..', 'docs', 'research', `energy-nuclear-preflight-${dateOnly}.md`);
  // Append to today's preflight doc if it exists, otherwise create a stub
  if (fs.existsSync(docPath)) {
    fs.appendFileSync(docPath, lines.join('\n'));
    console.log(`Appended live-hours probe to ${docPath}`);
  } else {
    const header = `# Energy + Nuclear ETF preflight — live-hours probe — ${dateOnly}\n\nGenerated by \`scripts/probe-energy-etf-quotes.js\`. No allocation decision.\n`;
    fs.writeFileSync(docPath, header + lines.join('\n'));
    console.log(`Created ${docPath}`);
  }

  console.log('');
  console.log('Summary:');
  for (const r of results) console.log('  ' + formatRow(r));
}

main().catch((err) => {
  console.error('probe failed:', err.stack || String(err));
  process.exit(1);
});
